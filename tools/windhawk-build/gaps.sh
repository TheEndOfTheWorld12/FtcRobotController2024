#!/bin/bash
# Generate a header filling in whatever this mingw-w64 sysroot is too old to
# declare. Windhawk's toolchain is newer and has all of it, so these gaps are
# an artifact of the local sysroot, not of any mod -- but left unfilled they
# show up as compile errors and look exactly like real bugs.
#
# Each entry is probed rather than assumed, so on a newer sysroot nothing is
# emitted and nothing collides.
#
#   gaps.sh <output header>
set -uo pipefail
OUT="${1:?usage: gaps.sh <output header>}"
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT

probe() {  # probe <expression using the symbol>
    cat > "$TMP/p.cpp" <<EOF
#include <windows.h>
#include <dwmapi.h>
#include <bluetoothapis.h>
#include <wlanapi.h>
#include <winerror.h>
void f() { (void)sizeof(decltype($1)); }
EOF
    clang++ --target=x86_64-w64-mingw32 -fsyntax-only \
        -DUNICODE -D_UNICODE -D_WIN32_WINNT=0x0A00 -DNOMINMAX \
        "$TMP/p.cpp" >/dev/null 2>&1
}

{
cat <<'EOF'
#pragma once
// Generated by tools/windhawk-build/gaps.sh. Only the declarations this
// sysroot is missing are emitted; a newer one produces an empty header.
EOF

probe 'E_BOUNDS' || echo '#define E_BOUNDS _HRESULT_TYPEDEF_(0x8000000BL)'
probe '(int)DWMWA_USE_IMMERSIVE_DARK_MODE' || echo '#define DWMWA_USE_IMMERSIVE_DARK_MODE 20'
probe '(int)DWMWA_WINDOW_CORNER_PREFERENCE' || echo '#define DWMWA_WINDOW_CORNER_PREFERENCE 33'
probe '(int)DWMWCP_ROUNDSMALL' || cat <<'EOF'
typedef enum {
    DWMWCP_DEFAULT = 0,
    DWMWCP_DONOTROUND = 1,
    DWMWCP_ROUND = 2,
    DWMWCP_ROUNDSMALL = 3,
} DWM_WINDOW_CORNER_PREFERENCE;
EOF
probe 'BLUETOOTH_SERVICE_ENABLE' || cat <<'EOF'
#define BLUETOOTH_SERVICE_DISABLE 0x00
#define BLUETOOTH_SERVICE_ENABLE  0x01
EOF
probe 'WLAN_AVAILABLE_NETWORK_CONNECTED' || cat <<'EOF'
#define WLAN_AVAILABLE_NETWORK_CONNECTED                           0x00000001
#define WLAN_AVAILABLE_NETWORK_HAS_PROFILE                         0x00000002
#define WLAN_AVAILABLE_NETWORK_INCLUDE_ALL_MANUAL_HIDDEN_PROFILES  0x00000004
EOF
} > "$OUT"

printf 'wrote %s (%d lines)\n' "$OUT" "$(wc -l < "$OUT")"
